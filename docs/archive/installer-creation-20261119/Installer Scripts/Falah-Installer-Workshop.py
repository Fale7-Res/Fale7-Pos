    def start_payload_build(self) -> None:
        if self.build_running:
            return
        if not BUILD_PAYLOAD.is_file() or not BUILD_INSTALLER.is_file():
            messagebox.showerror("ملفات البناء غير موجودة", "تحقق من وجود Build-Payload.ps1 وBuild-Installer.ps1 داخل Installer Creation.")
            return
        if not POWERSHELL.is_file():
            messagebox.showerror("PowerShell غير موجود", f"لم يتم العثور على Windows PowerShell في:\n{POWERSHELL}")
            return
        self.build_running = True
        self.build_stage = "payload"
        self.build_button.configure(state="disabled")
        self.build_status.set("جاري بناء الوحدات الأربعة…")
        self._append_build_log("\n=== بدء إعادة بناء الوحدات ===\n")
        self._start_process(BUILD_PAYLOAD, "payload")

    def _start_process(self, script: Path, stage: str) -> None:
        LOGS.mkdir(parents=True, exist_ok=True)
        log_path = LOGS / ("workshop-" + stage + ".log")
        command = [str(POWERSHELL), "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(script)]
        if stage == "installer":
            command.append("-SkipPublish")

        def worker() -> None:
            try:
                startupinfo = subprocess.STARTUPINFO()
                startupinfo.dwFlags |= subprocess.STARTF_USESHOWWINDOW
                startupinfo.wShowWindow = 0
                with log_path.open("w", encoding="utf-8", errors="replace") as log_file:
                    process = subprocess.Popen(
                        command,
                        cwd=str(REPO_ROOT),
                        stdout=subprocess.PIPE,
                        stderr=subprocess.STDOUT,
                        text=True,
                        encoding="utf-8",
                        errors="replace",
                        startupinfo=startupinfo,
                        creationflags=subprocess.CREATE_NO_WINDOW,
                    )
                    assert process.stdout is not None
                    for line in process.stdout:
                        log_file.write(line)
                        log_file.flush()
                        self.events.put(("line", stage, line))
                    code = process.wait()
                self.events.put(("done", stage, code, str(log_path)))
            except Exception as exc:  # surface process launch and log-write failures in the UI
                self.events.put(("exception", stage, str(exc), str(log_path)))

        threading.Thread(target=worker, daemon=True).start()

    def _poll_build_events(self) -> None:
        try:
            while True:
                event = self.events.get_nowait()
                if event[0] == "line":
                    self._append_build_log(event[2])
                elif event[0] == "exception":
                    _, stage, error, log_path = event
                    self._finish_build(False)
                    self.build_status.set(f"فشل تشغيل مرحلة {stage}")
                    messagebox.showerror("فشل البناء", f"{error}\n\nالسجل: {log_path}")
                elif event[0] == "done":
                    _, stage, code, log_path = event
                    if code != 0:
                        self._finish_build(False)
                        self.build_status.set(f"فشل البناء (exit code {code})")
                        messagebox.showerror("فشل البناء", f"مرحلة {stage} فشلت برمز {code}.\n\nراجع:\n{log_path}")
                        continue
                    if stage == "payload":
                        self.build_status.set("اكتمل بناء كل الوحدات.")
                        self._append_build_log("=== اكتمل بناء الوحدات ===\n")
                        proceed = messagebox.askyesno(
                            "اكتمل البناء",
                            "اكتمل بناء الوحدات الأربعة. هل تريد متابعة تجميع المثبّت التنفيذي؟",
                        )
                        if proceed:
                            self.build_stage = "installer"
                            self.build_status.set("جاري تجميع Falah-Restaurant-Setup.exe…")
                            self._append_build_log("\n=== بدء تجميع المثبّت ===\n")
                            self._start_process(BUILD_INSTALLER, "installer")
                        else:
                            self._finish_build(False)
                            messagebox.showinfo(
                                "انتهى بناء الوحدات",
                                f"توقفت قبل تجميع المثبّت. ملفات الوحدات موجودة في:\n{WORKSPACE / 'Application Builds'}",
                            )
                    else:
                        self._finish_build(True)
                        self.build_status.set(f"اكتمل المثبّت: {INSTALLER_EXE}")
                        hash_path = OUTPUT / "Falah-Restaurant-Setup.sha256.txt"
                        hash_note = f"\n\nSHA-256: {hash_path}" if hash_path.is_file() else ""
                        messagebox.showinfo(
                            "اكتمل المثبّت",
                            f"تم بناء ملف التثبيت بنجاح:\n{INSTALLER_EXE}{hash_note}",
                        )
        except queue.Empty:
            pass
        self.root.after(100, self._poll_build_events)

    def _finish_build(self, completed: bool) -> None:
        self.build_running = False
        self.build_stage = None
        self.build_button.configure(state="normal")
        if completed:
            self.build_status.set(f"اكتمل: {INSTALLER_EXE}")


