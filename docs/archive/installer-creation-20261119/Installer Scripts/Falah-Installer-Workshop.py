    def generate_cleanup(self) -> None:
        mode = self.db_mode.get()
        name = self.db_name.get().strip()
        if mode == "falah" and not name:
            messagebox.showerror("اسم قاعدة البيانات مطلوب", "اكتب اسم قاعدة البيانات التي تريد مسحها.")
            return
        selected = self.remove_app_var.get() or self.clear_data_var.get() or self.uninstall_sql_var.get() or mode != "none"
        if not selected:
            messagebox.showwarning("لا توجد اختيارات", "حدد عملية واحدة على الأقل لتوليد سكريبتها.")
            return
        try:
            self.cleanup_script = render_cleanup_script(
                self.remove_app_var.get(), self.clear_data_var.get(), mode, name, self.uninstall_sql_var.get()
            )
        except ValueError as exc:
            messagebox.showerror("تعذر توليد السكريبت", str(exc))
            return
        self.cleanup_preview.delete("1.0", "end")
        self.cleanup_preview.insert("1.0", self.cleanup_script)

    def copy_cleanup(self) -> None:
        if not self.cleanup_script:
            self.generate_cleanup()
        if not self.cleanup_script:
            return
        self.root.clipboard_clear()
        self.root.clipboard_append(self.cleanup_script)
        self.root.update()
        messagebox.showinfo("تم النسخ", "تم نسخ سكريبت PowerShell إلى الحافظة.")

