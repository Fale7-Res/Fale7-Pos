def render_cleanup_script(
    remove_application: bool,
    clear_falah_data: bool,
    database_mode: str,
    falah_database_name: str,
    uninstall_sql_engines: bool,
) -> str:
    """Create a local-machine cleanup script with the exact choices selected in the GUI."""
    if database_mode not in {"none", "falah", "all"}:
        raise ValueError("Unknown database cleanup mode")
    if database_mode == "falah" and not falah_database_name.strip():
        raise ValueError("Enter the database name to remove")
    db_name = falah_database_name.replace("'", "''")
    script = r'''#requires -Version 5.1
#requires -RunAsAdministrator
# Falah cleanup plan generated by Falah Installer Workshop.
# Scope: this computer's Falah installation and/or local SQL Server Database Engine instances.
# It never connects to remote SQL servers. Run from an elevated 64-bit Windows PowerShell.
$ErrorActionPreference = 'Stop'
$RemoveFalahApplication = __REMOVE_APP__
$ClearFalahProgramData = __CLEAR_FALAH_DATA__
$DatabaseCleanupMode = '__DB_MODE__' # none, falah, or all local user databases
$FalahDatabaseName = '__DB_NAME__'
$UninstallSqlEngineInstances = __UNINSTALL_SQL__
$currentIdentity = [Security.Principal.WindowsIdentity]::GetCurrent()
$currentPrincipal = New-Object Security.Principal.WindowsPrincipal($currentIdentity)
if (-not $currentPrincipal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Host 'Cleanup stopped before making changes: this PowerShell session is not elevated.' -ForegroundColor Red
    Write-Host 'Open Windows PowerShell with Run as administrator, then run the saved .ps1 file or paste the generated script there.'
    if ($Host.Name -eq 'ConsoleHost') {
        Read-Host 'Press Enter to close this window' | Out-Null
    }
    return
}
$logRoot = Join-Path $env:ProgramData 'Falah-Cleanup\Logs'
New-Item -ItemType Directory -Path $logRoot -Force | Out-Null
$logPath = Join-Path $logRoot ('cleanup-' + (Get-Date -Format 'yyyyMMdd-HHmmss') + '.log')
Start-Transcript -Path $logPath -Force | Out-Null

function Get-SqlEngineInstances {
    $registryPath = 'HKLM:\SOFTWARE\Microsoft\Microsoft SQL Server\Instance Names\SQL'
    if (-not (Test-Path -LiteralPath $registryPath)) { return @() }
    $properties = (Get-ItemProperty -LiteralPath $registryPath).PSObject.Properties |
        Where-Object { $_.Name -notlike 'PS*' }
    $found = @()
    foreach ($property in $properties) {
        $instanceName = [string]$property.Name
        $instanceId = [string]$property.Value
        $versionPath = "HKLM:\SOFTWARE\Microsoft\Microsoft SQL Server\$instanceId\MSSQLServer\CurrentVersion"
        $version = (Get-ItemProperty -LiteralPath $versionPath -ErrorAction SilentlyContinue).CurrentVersion
        $serviceName = if ($instanceName -eq 'MSSQLSERVER') { 'MSSQLSERVER' } else { 'MSSQL$' + $instanceName }
        $service = Get-Service -Name $serviceName -ErrorAction SilentlyContinue
        $found += [pscustomobject]@{
            Name = $instanceName
            Id = $instanceId
            Version = [string]$version
            ServiceName = $serviceName
            ServiceStatus = if ($service) { [string]$service.Status } else { 'Not found' }
        }
    }
    return $found
}

function New-MasterConnection([string]$instanceName) {
    $dataSource = if ($instanceName -eq 'MSSQLSERVER') { 'localhost' } else { 'localhost\' + $instanceName }
    $builder = New-Object System.Data.SqlClient.SqlConnectionStringBuilder
    $builder['Data Source'] = $dataSource
    $builder['Initial Catalog'] = 'master'
    $builder['Integrated Security'] = $true
    $builder['TrustServerCertificate'] = $true
    $builder['Connect Timeout'] = 8
    return New-Object System.Data.SqlClient.SqlConnection($builder.ConnectionString)
}

function Get-SetupExe([pscustomobject]$instance) {
    if ([string]::IsNullOrWhiteSpace($instance.Version)) { return $null }
    $major = [int]($instance.Version.Split('.')[0])
    $versionFolder = ('{0}0' -f $major)
    $roots = @()
    foreach ($programFiles in @(${env:ProgramFiles}, ${env:ProgramFiles(x86)})) {
        if ($programFiles) { $roots += (Join-Path $programFiles "Microsoft SQL Server\$versionFolder\Setup Bootstrap") }
    }
    $candidates = @()
    foreach ($root in $roots | Select-Object -Unique) {
        if (-not (Test-Path -LiteralPath $root)) { continue }
        $direct = Join-Path $root 'setup.exe'
        if (Test-Path -LiteralPath $direct) { $candidates += Get-Item -LiteralPath $direct }
        foreach ($directory in Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue) {
            if ($directory.Name -notlike 'SQL*') { continue }
            $candidate = Join-Path $directory.FullName 'setup.exe'
            if (Test-Path -LiteralPath $candidate) { $candidates += Get-Item -LiteralPath $candidate }
        }
    }
    foreach ($candidate in $candidates) {
        $signature = Get-AuthenticodeSignature -LiteralPath $candidate.FullName
        if ($signature.Status -eq 'Valid' -and $signature.SignerCertificate.Subject -like '*Microsoft*') {
            return $candidate.FullName
        }
    }
    return $null
}

function Resolve-FalahInstallRoot {
    $candidates = @()
    $statePath = Join-Path $env:ProgramData 'Falah\install-state.json'
    if (Test-Path -LiteralPath $statePath) {
        try { $state = Get-Content -LiteralPath $statePath -Raw | ConvertFrom-Json; $candidates += [string]$state.InstallRoot } catch { }
    }
    $installerKey = 'HKLM:\SOFTWARE\Falah\Restaurant\Installer'
    if (Test-Path -LiteralPath $installerKey) {
        $candidates += [string](Get-ItemProperty -LiteralPath $installerKey -ErrorAction SilentlyContinue).InstallRoot
    }
    $uninstallRoots = @(
        'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall',
        'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall'
    )
    foreach ($uninstallRoot in $uninstallRoots) {
        if (-not (Test-Path -LiteralPath $uninstallRoot)) { continue }
        foreach ($key in Get-ChildItem -LiteralPath $uninstallRoot -ErrorAction SilentlyContinue) {
            $entry = Get-ItemProperty -LiteralPath $key.PSPath -ErrorAction SilentlyContinue
            if ($entry.DisplayName -eq 'Falah Restaurant' -or $key.PSChildName -like '*C547D919-BE32-4DE9-B7AE-1CC50F56D98D*') {
                if ($entry.InstallLocation) { $candidates += [string]$entry.InstallLocation }
                if ($entry.UninstallString -match '^\s*"?(.+?unins\d+\.exe)') {
                    $candidates += Split-Path -Parent $Matches[1]
                }
            }
        }
    }
    $candidates += (Join-Path ${env:ProgramFiles} 'Falah Restaurant')
    foreach ($candidate in $candidates | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Select-Object -Unique) {
        try { $full = [IO.Path]::GetFullPath($candidate).TrimEnd('\') } catch { continue }
        if ((Test-Path -LiteralPath (Join-Path $full 'unins000.exe')) -and
            (Test-Path -LiteralPath (Join-Path $full 'Deployment\Uninstall-Deployment.ps1')) -and
            (Test-Path -LiteralPath (Join-Path $full 'Server\Falah.Server.exe'))) {
            return $full
        }
    }
    # Inno removes its registration and tracked payload before reporting success.
    # The deployment-generated Production config is excluded from Inno's file list,
    # so it can be the only Falah-owned evidence left after a completed uninstall.
    $defaultRoot = Join-Path ${env:ProgramFiles} 'Falah Restaurant'
    $residualConfig = Join-Path $defaultRoot 'Server\appsettings.Production.json'
    $knownExecutables = @(
        'Cashier\Falah.Client.CashierWinUI.exe',
        'CallCenter\Falah.Client.CallCenterWinUI.exe',
        'Server\Falah.Server.exe',
        'PrintAgent\Falah.PrintAgent.exe',
        'unins000.exe'
    )
    $knownPayloadRemains = @($knownExecutables | Where-Object { Test-Path -LiteralPath (Join-Path $defaultRoot $_) })
    if ((Test-Path -LiteralPath $residualConfig) -and $knownPayloadRemains.Count -eq 0) {
        return $defaultRoot
    }
    return $null
}

function Stop-FalahServerIfOwned([string]$installRoot) {
    $service = Get-CimInstance Win32_Service -Filter "Name='FalahServer'" -ErrorAction SilentlyContinue
    if (-not $service) { return }
    if ([string]::IsNullOrWhiteSpace($installRoot)) {
        throw "FalahServer is installed but its Falah installation path could not be verified. It was left running."
    }
    $expectedExe = [IO.Path]::GetFullPath((Join-Path $installRoot 'Server\Falah.Server.exe'))
    if ($service.PathName -notlike "*$expectedExe*") {
        throw "Service FalahServer points outside the verified Falah installation and was left untouched."
    }
    if ($service.State -eq 'Running') {
        Stop-Service -Name 'FalahServer' -Force
        (Get-Service -Name 'FalahServer').WaitForStatus('Stopped',[TimeSpan]::FromSeconds(30))
    }
}

function Get-UserDatabases([pscustomobject]$instance) {
    $connection = New-MasterConnection $instance.Name
    try {
        $connection.Open()
        $command = $connection.CreateCommand()
        $command.CommandText = 'SELECT name, state_desc FROM sys.databases WHERE database_id > 4 ORDER BY name'
        $reader = $command.ExecuteReader()
        $databases = @()
        try {
            while ($reader.Read()) {
                $databases += [pscustomobject]@{ Name=[string]$reader['name']; State=[string]$reader['state_desc'] }
            }
        } finally { $reader.Dispose(); $command.Dispose() }
        return $databases
    } finally { $connection.Dispose() }
}

function Remove-SelectedDatabase([pscustomobject]$instance, [pscustomobject]$database) {
    $connection = New-MasterConnection $instance.Name
    try {
        $connection.Open()
        $safeName = '[' + $database.Name.Replace(']', ']]') + ']'
        $command = $connection.CreateCommand()
        if ($database.State -eq 'ONLINE') {
            $command.CommandText = "ALTER DATABASE $safeName SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE $safeName;"
        } else {
            $command.CommandText = "DROP DATABASE $safeName;"
        }
        $null = $command.ExecuteNonQuery()
        $command.Dispose()
        Write-Host "Removed database '$($database.Name)' from instance '$($instance.Name)'."
    } finally { $connection.Dispose() }
}

try {
    if (-not [Environment]::Is64BitProcess) { throw 'Use 64-bit Windows PowerShell for SQL Server instance discovery.' }
    $instances = @(Get-SqlEngineInstances)
    $databasesByInstance = @{}
    $setupByInstance = @{}

    if ($DatabaseCleanupMode -ne 'none') {
        Add-Type -AssemblyName System.Data
        foreach ($instance in $instances) {
            Write-Host "Checking local SQL instance '$($instance.Name)'..."
            # Complete discovery and permission checks for every local instance before deleting anything.
            $databasesByInstance[$instance.Name] = @(Get-UserDatabases $instance)
        }
    }
    if ($UninstallSqlEngineInstances) {
        foreach ($instance in $instances) {
            $setup = Get-SetupExe $instance
            if (-not $setup) {
                throw "Could not find a signed Microsoft SQL Server Setup executable for instance '$($instance.Name)' (version $($instance.Version)). No SQL instance was removed. Supply matching installation media or uninstall it from Windows Settings."
            }
            $setupByInstance[$instance.Name] = $setup
        }
    }

    $plannedDatabases = @()
    foreach ($instance in $instances) {
        foreach ($database in @($databasesByInstance[$instance.Name])) {
            if ($DatabaseCleanupMode -eq 'all' -or
                ($DatabaseCleanupMode -eq 'falah' -and $database.Name -eq $FalahDatabaseName)) {
                $plannedDatabases += [pscustomobject]@{ Instance=$instance; Database=$database }
            }
        }
    }

    $appRoot = Resolve-FalahInstallRoot
    $uninstallerCandidate = if ($appRoot) { Join-Path $appRoot 'unins000.exe' } else { $null }
    $uninstaller = if ($uninstallerCandidate -and (Test-Path -LiteralPath $uninstallerCandidate -PathType Leaf)) { $uninstallerCandidate } else { $null }
    $partialAppRoot = $appRoot -and -not $uninstaller -and
        (Test-Path -LiteralPath (Join-Path $appRoot 'Server\appsettings.Production.json'))
    if ($RemoveFalahApplication -and -not $uninstaller -and -not $partialAppRoot) {
        throw 'Could not verify a Falah installation and its registered uninstaller. No cleanup action has run. Use Windows Settings > Installed apps to remove the Falah application first.'
    }

    Write-Host ''
    Write-Host 'Selected cleanup plan:'
    if ($RemoveFalahApplication -and $uninstaller) { Write-Host " - Uninstall Falah application from: $appRoot" }
    if ($RemoveFalahApplication -and $partialAppRoot) { Write-Host " - Remove verified residual files from a previously uninstalled Falah application: $appRoot" }
    if ($ClearFalahProgramData) { Write-Host " - Permanently remove: $env:ProgramData\Falah (includes backups, logs, TLS files, and install state)" }
    if ($DatabaseCleanupMode -eq 'falah') { Write-Host " - Remove only database named '$FalahDatabaseName' from local SQL instances" }
    if ($DatabaseCleanupMode -eq 'all') { Write-Host ' - Remove every user database from every reachable local SQL Server Engine instance' }
    foreach ($item in $plannedDatabases) { Write-Host "   database: $($item.Database.Name) [$($item.Database.State)] on $($item.Instance.Name)" }
    if ($DatabaseCleanupMode -eq 'all' -and $plannedDatabases.Count -eq 0) { Write-Host '   no user databases were found' }
    if ($UninstallSqlEngineInstances) {
        if ($instances.Count -eq 0) { Write-Host ' - No SQL Server Database Engine instances were found' }
        foreach ($instance in $instances) { Write-Host " - Uninstall SQL Server Engine instance '$($instance.Name)' ($($instance.Version)); Setup: $($setupByInstance[$instance.Name])" }
        if ($DatabaseCleanupMode -eq 'none') { Write-Warning 'Database files may remain on disk when SQL Server is uninstalled without first selecting a database cleanup option.' }
    }
    if ($plannedDatabases.Count -gt 0 -and $DatabaseCleanupMode -eq 'all') {
        Write-Warning 'This deletes databases unrelated to Falah too. System databases are excluded.'
    }
    if (-not ($RemoveFalahApplication -or $ClearFalahProgramData -or $DatabaseCleanupMode -ne 'none' -or $UninstallSqlEngineInstances)) {
        throw 'No cleanup action was selected.'
    }

    Write-Host ''
    $confirmation = Read-Host 'To execute this exact plan, type WIPE SELECTED DATA'
    if ($confirmation -cne 'WIPE SELECTED DATA') { throw 'Confirmation did not match. No cleanup action was run.' }

    if ($DatabaseCleanupMode -ne 'none' -or $UninstallSqlEngineInstances) { Stop-FalahServerIfOwned $appRoot }

    if ($RemoveFalahApplication -and $partialAppRoot) {
        Write-Host "Removing verified leftovers from the previous Falah uninstall: $appRoot"
        Remove-Item -LiteralPath $appRoot -Recurse -Force
        if (Test-Path -LiteralPath $appRoot) { throw "Residual Falah files remain under $appRoot. Remaining cleanup actions were stopped." }
        Write-Host 'Residual Falah application files removed.'
    }

    if ($RemoveFalahApplication -and $uninstaller) {
        $uninstallLog = Join-Path $logRoot ('falah-uninstall-' + (Get-Date -Format 'yyyyMMdd-HHmmss') + '.log')
        Write-Host "Running the registered Falah uninstaller. Its detailed log will be: $uninstallLog"
        $uninstallArguments = '/VERYSILENT /SUPPRESSMSGBOXES /NORESTART /LOG="' + $uninstallLog + '"'
        $process = Start-Process -FilePath $uninstaller -ArgumentList $uninstallArguments -Wait -PassThru
        if (-not (Test-Path -LiteralPath $uninstallLog)) {
            throw "Falah uninstaller did not create its expected log (exit code $($process.ExitCode)): $uninstallLog. Remaining cleanup actions were stopped."
        }
        $uninstallLogText = Get-Content -LiteralPath $uninstallLog -Raw
        $innoReportedSuccess = $uninstallLogText.Contains('Uninstallation process succeeded.') -and
            $uninstallLogText.Contains('Removed all? Yes')
        $remainingPayload = @(
            'Cashier\Falah.Client.CashierWinUI.exe',
            'CallCenter\Falah.Client.CallCenterWinUI.exe',
            'Server\Falah.Server.exe',
            'PrintAgent\Falah.PrintAgent.exe'
        ) | Where-Object { Test-Path -LiteralPath (Join-Path $appRoot $_) }
        if ($process.ExitCode -ne 0 -and -not $innoReportedSuccess) {
            throw "Falah uninstaller failed with exit code $($process.ExitCode), and its log has no successful completion marker. Review: $uninstallLog. Remaining cleanup actions were stopped."
        }
        if ($remainingPayload.Count -gt 0) {
            throw "Falah uninstaller reported exit code $($process.ExitCode) but application executable(s) remain: $($remainingPayload -join ', '). Review: $uninstallLog. Remaining cleanup actions were stopped."
        }
        if ($process.ExitCode -ne 0) {
            Write-Warning "Inno Setup returned exit code $($process.ExitCode), but its completed log confirms successful removal and the application executables are gone. Continuing with the selected cleanup."
        }
        # Deployment creates this protected config after Inno records installed files.
        # The user explicitly selected app removal, so clear any residual content in
        # this already-verified Falah installation directory after Inno confirms success.
        if (Test-Path -LiteralPath $appRoot) {
            Remove-Item -LiteralPath $appRoot -Recurse -Force
            if (Test-Path -LiteralPath $appRoot) { throw "Falah uninstall completed, but residual files remain under $appRoot. Remaining cleanup actions were stopped." }
        }
        Write-Host 'Falah application uninstalled. SQL Server and databases were not touched by this action.'
    }

    foreach ($item in $plannedDatabases) { Remove-SelectedDatabase $item.Instance $item.Database }

    if ($ClearFalahProgramData) {
        $falahData = Join-Path $env:ProgramData 'Falah'
        if (Test-Path -LiteralPath $falahData) {
            Remove-Item -LiteralPath $falahData -Recurse -Force
            Write-Host "Removed Falah ProgramData: $falahData"
        } else { Write-Host 'Falah ProgramData was not present.' }
    }

    if ($UninstallSqlEngineInstances) {
        foreach ($instance in $instances) {
            Write-Host "Uninstalling local SQL Server Engine '$($instance.Name)'..."
            $arguments = @('/Q','/ACTION=Uninstall','/FEATURES=SQL',('/INSTANCENAME=' + $instance.Name))
            $process = Start-Process -FilePath $setupByInstance[$instance.Name] -ArgumentList $arguments -Wait -PassThru
            if ($process.ExitCode -notin @(0,3010)) { throw "SQL Server Setup failed for '$($instance.Name)' with exit code $($process.ExitCode). Review its Setup Bootstrap logs." }
            if (Get-Service -Name $instance.ServiceName -ErrorAction SilentlyContinue) {
                throw "SQL Server Setup returned success but service '$($instance.ServiceName)' remains. Review SQL Setup logs before retrying."
            }
        }
    }
    Write-Host 'Selected cleanup actions completed.'
    Write-Host "Log: $logPath"
} catch {
    $cleanupError = $_
    Write-Host "Cleanup stopped: $($cleanupError.Exception.Message)" -ForegroundColor Red
    Write-Host "Failed command: $($cleanupError.InvocationInfo.Line)"
    Write-Host "Script location: $($cleanupError.InvocationInfo.ScriptName):$($cleanupError.InvocationInfo.ScriptLineNumber)"
    Write-Host "Log: $logPath"
} finally {
    Stop-Transcript | Out-Null
}
if ($cleanupError) {
    if ($Host.Name -eq 'ConsoleHost') {
        Read-Host 'Press Enter to close this window after reviewing the error and log path' | Out-Null
    }
    throw $cleanupError
}
'''
    replacements = {
        "__REMOVE_APP__": "$true" if remove_application else "$false",
        "__CLEAR_FALAH_DATA__": "$true" if clear_falah_data else "$false",
        "__DB_MODE__": database_mode,
        "__DB_NAME__": db_name,
        "__UNINSTALL_SQL__": "$true" if uninstall_sql_engines else "$false",
    }
    for token, value in replacements.items():
        script = script.replace(token, value)
    return script


